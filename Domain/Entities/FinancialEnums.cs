namespace PunchedApi.Domain.Entities;

/// <summary>
/// What a financial ledger row represents in the business's money movement.
///
/// <para>Deliberately a different axis from <see cref="TransactionSource"/>: the type
/// says <i>which direction and kind</i> the money moved, the source says <i>where the
/// business transaction came from</i>.</para>
/// </summary>
public enum FinancialTransactionType
{
    /// <summary>Money received by the business (appointment, walk-in, product, manual).</summary>
    Income = 0,

    /// <summary>Money spent by the business (rent, salaries, stock, …).</summary>
    Expense = 1,

    /// <summary>Money returned to a customer against an earlier income row.</summary>
    Refund = 2,

    /// <summary>A correction recorded by the owner (rounding, mis-posted amount).</summary>
    Adjustment = 3
}

/// <summary>
/// Where a business transaction originated. Answers "did Punched see this happen, or
/// did the owner record something that happened entirely outside Punched?".
/// </summary>
public enum TransactionSource
{
    /// <summary>Generated by an appointment booked through Punched (booking fee, balance, full).</summary>
    PunchedBooking = 0,

    /// <summary>A customer who walked in and paid without an appointment.</summary>
    WalkIn = 1,

    /// <summary>A product sale (retail item) rather than a service.</summary>
    ProductSale = 2,

    /// <summary>Income the owner recorded by hand with no Punched counterpart.</summary>
    ManualIncome = 3,

    /// <summary>Anything else (grants, pooled tips, adjustments).</summary>
    Other = 4
}

/// <summary>
/// How the business received (or paid) the money. Wider than the appointment payment
/// methods: a walk-in customer may pay by Till, Paybill, Send Money, cash, bank
/// transfer or card, and none of those need a Punched appointment.
/// </summary>
public enum FinancialPaymentMethod
{
    MpesaTill = 0,
    MpesaPaybill = 1,
    MpesaSendMoney = 2,
    Cash = 3,
    BankTransfer = 4,
    Card = 5,
    Other = 6
}

/// <summary>
/// Whether the money on a ledger row is confirmed.
///
/// <para>Independent of <see cref="ReconciliationStatus"/>: an owner confirming a
/// pasted M-Pesa message makes a row <see cref="Verified"/>, but it stays
/// <see cref="ReconciliationStatus.Unreconciled"/> until it has been compared against
/// the business's actual M-Pesa statement.</para>
/// </summary>
public enum FinancialVerificationStatus
{
    /// <summary>Recorded but not yet confirmed — never counts as recognised revenue.</summary>
    Pending = 0,

    /// <summary>Confirmed by the owner (or by a provider callback). Counts as revenue.</summary>
    Verified = 1,

    /// <summary>Refused (wrong amount, unknown transaction, reused code). Never counts as revenue.</summary>
    Rejected = 2
}

/// <summary>
/// Which way the money moved.
///
/// <para><b>Its own axis, deliberately.</b> Direction is not the type, the source or the category:
/// an expense is <see cref="Outgoing"/> whether it was paid by cash, M-Pesa or bank transfer, and a
/// refund is <see cref="Outgoing"/> even though it originates from an incoming payment. Inferring
/// direction from a description or a UI label is how a refund ends up counted as income, so the
/// server states it explicitly and every screen reads this field rather than guessing.</para>
/// </summary>
public enum FinancialDirection
{
    /// <summary>Money the business received (income, adjustments).</summary>
    Incoming = 0,

    /// <summary>Money the business paid out or returned (expenses, refunds).</summary>
    Outgoing = 1
}

/// <summary>How far a ledger row has got against the business's real M-Pesa statement.</summary>
public enum ReconciliationStatus
{
    /// <summary>Not yet compared with any statement.</summary>
    Unreconciled = 0,

    /// <summary>Matched to an imported statement line (or manually matched).</summary>
    Matched = 1,

    /// <summary>Compared and found to differ, or an imported line with no counterpart.</summary>
    Discrepancy = 2,

    /// <summary>Deliberately excluded from reconciliation (e.g. a duplicate statement line).</summary>
    Excluded = 3
}

/// <summary>
/// The predefined expense categories. Keys are stable and stored on the ledger row, so
/// adding a category is a code change (no migration) and historical rows keep meaning
/// exactly what they meant when they were recorded.
/// </summary>
public static class ExpenseCategories
{
    public const string Rent = "rent";
    public const string Salaries = "salaries";
    public const string Utilities = "utilities";
    public const string StockAndSupplies = "stock_and_supplies";
    public const string Equipment = "equipment";
    public const string Transport = "transport";
    public const string Marketing = "marketing";
    public const string Maintenance = "maintenance";
    public const string InternetAndCommunication = "internet_and_communication";
    public const string Other = "other";

    /// <summary>Every known key, in the order the UI should offer them.</summary>
    public static readonly IReadOnlyList<string> All = new[]
    {
        Rent, Salaries, Utilities, StockAndSupplies, Equipment,
        Transport, Marketing, Maintenance, InternetAndCommunication, Other
    };

    /// <summary>Human label for a key (the UI may localise; the API stays canonical).</summary>
    public static string Label(string key) => key switch
    {
        Rent => "Rent",
        Salaries => "Salaries",
        Utilities => "Utilities",
        StockAndSupplies => "Stock and supplies",
        Equipment => "Equipment",
        Transport => "Transport",
        Marketing => "Marketing",
        Maintenance => "Maintenance",
        InternetAndCommunication => "Internet and communication",
        Other => "Other",
        _ => key
    };

    /// <summary>True when the key is one of the predefined categories.</summary>
    public static bool IsKnown(string? key) => key != null && All.Contains(key, StringComparer.Ordinal);

    /// <summary>
    /// Normalises a client value to a known key, or null when it is not one — so a
    /// caller can never store a free-text category the expense filter could not offer.
    /// </summary>
    public static string? Normalise(string? value)
    {
        if (string.IsNullOrWhiteSpace(value)) return null;

        var folded = value.Trim().ToLowerInvariant().Replace('-', '_').Replace(' ', '_');
        return IsKnown(folded) ? folded : null;
    }
}
